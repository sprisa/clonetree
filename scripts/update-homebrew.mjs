import { execFileSync } from 'node:child_process';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const [tap, repository = 'sprisa/clonetree'] = process.argv.slice(2);
if (!tap || !statSync(tap).isDirectory()) {
  throw new Error('Usage: node scripts/update-homebrew.mjs <homebrew-tap-directory> [owner/repo]');
}
const version = readFileSync(new URL('../version.txt', import.meta.url), 'utf8').trim();
if (!version) throw new Error('version.txt must not be empty');

// Read the published checksums, so rebuilding locally cannot change the formula's hashes.
const text = execFileSync('gh', [
  'release', 'download', `v${version}`, '--repo', repository,
  '--pattern', 'checksums.txt', '--output', '-',
], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
const checksums = new Map();
for (const line of text.split('\n')) {
  const match = /^([a-f0-9]{64})\s+\*?(.+)$/.exec(line.trim());
  if (match) checksums.set(match[2], match[1]);
}

const base = `https://github.com/${repository}/releases/download/v${version}`;
function platform(os, arch) {
  const asset = `clonetree_${os}_${arch}.tar.gz`;
  const sha = checksums.get(asset);
  if (!sha) throw new Error(`Published checksums are missing ${asset}`);
  return `      url "${base}/${asset}"
      sha256 "${sha}"`;
}

const formula = `# typed: false
# frozen_string_literal: true

# Generated by clonetree's scripts/update-homebrew.mjs.
class Clonetree < Formula
  desc "Copy-on-write snapshots of directories"
  homepage "https://github.com/${repository}"
  version "${version}"
  license "MPL-2.0"

  on_macos do
    on_arm do
${platform('Darwin', 'arm64')}
    end
    on_intel do
${platform('Darwin', 'x86_64')}
    end
  end

  on_linux do
    on_arm do
${platform('Linux', 'arm64')}
    end
    on_intel do
${platform('Linux', 'x86_64')}
    end
  end

  def install
    bin.install "clonetree"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/clonetree --version")
    system bin/"clonetree", "init"
    assert_match "*.clonetree/", (testpath/".gitignore").read
  end
end
`;

const path = resolve(tap, 'clonetree.rb');
writeFileSync(path, formula);
console.log(`Updated ${path} for v${version}`);
